// Cross-chunk safety net: esbuild may hoist `__hermesT` into the entry
// chunk while some screens import it from a different chunk, leaving the
// imported binding `undefined` at runtime (ReferenceError: t is not defined).
// Registering it on globalThis lets every importer fall back to it.
if (typeof globalThis !== 'undefined') {
  ;(globalThis as unknown as { __hermesT?: unknown }).__hermesT = __hermesT
  ;(globalThis as unknown as { __HERMES_LOCALES__?: unknown }).__HERMES_LOCALES__ = LOCALES
}
