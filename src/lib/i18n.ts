const STORAGE_KEY = 'hermes-workspace-locale'

export function getLocale(): LocaleId {
  if (typeof window === 'undefined') return 'en'
  const stored = localStorage.getItem(STORAGE_KEY)
  if (stored && stored in LOCALES) return stored as LocaleId
  const full = navigator.language
  if (full in LOCALES) return full as LocaleId
  const lang = full.split('-')[0]
  if (lang in LOCALES) return lang as LocaleId
  return 'en'
}

export function setLocale(id: LocaleId): void {
  localStorage.setItem(STORAGE_KEY, id)
  window.dispatchEvent(new CustomEvent('locale-change', { detail: id }))
}

export function __hermesT(key: TranslationKey): string {
  const locale = getLocale()
  switch (locale) {
    case 'ru':
      return RU[key] ?? EN[key] ?? key
    case 'es':
      return ES[key] ?? EN[key] ?? key
    case 'fr':
      return FR[key] ?? EN[key] ?? key
    case 'de':
      return EN[key] ?? key
    case 'zh':
      return ZH[key] ?? EN[key] ?? key
    case 'zh-TW':
      return ZH_TW[key] ?? EN[key] ?? key
    case 'ja':
      return JA[key] ?? EN[key] ?? key
    case 'ko':
      return EN[key] ?? key
    case 'pt':
      return EN[key] ?? key
    case 'ar':
      return EN[key] ?? key
    default:
      return EN[key] ?? key
  }
}

